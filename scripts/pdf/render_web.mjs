function read(p) {
  try {
    return readFileSync(p, "utf8");
  } catch {
    fail(`missing or unreadable source file: ${path.relative(REPO, p)}`);
  }
}

// ---------------------------------------------------------------------------
// Source manifest — mirrors build.py's section order.
// ---------------------------------------------------------------------------
const INDEX_ROW_RE = /^\|\s*[A-Z]{1,2}\s*\|.*\|\s*`([^`]+\.md)`\s*\|\s*$/;

function regionOrder() {
  const indexPath = path.join(REPO, "regions", "00_INDEX.md");
  const names = [];
  for (const line of read(indexPath).split("\n")) {
    const m = INDEX_ROW_RE.exec(line.trim());
    if (m) names.push(m[1]);
  }
  if (names.length === 0) fail(`no region rows parsed from regions/00_INDEX.md`);
  return names;
}

// Region display title, from the file's own "# `CODE Name`" line.
function titleOf(markdown, fallback) {
  const m = /^#\s+`?([^`\n]+)`?\s*$/m.exec(markdown);
  return m ? m[1].trim() : fallback;
}

function slugOf(fileName) {
  return fileName.replace(/\.md$/, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

