// Location code index — code -> page slug, built from stub headings.
// Same shape as check.py's STUB_HEADING_RE, so the site and the checks agree
// on what counts as a defined location.
// ---------------------------------------------------------------------------
const STUB_HEADING_RE = /^### `([A-Z]{1,2}\.[0-9]+[a-z]?) ([^`]+)`/;

