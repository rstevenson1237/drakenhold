#!/usr/bin/env node
// Renders the Drakenhold sources to a browsable static site in build/web/.
//
// Usage: node render_web.mjs [OUT_DIR]
//
// Sibling of render.mjs and deliberately built on the same toolchain: mermaid
// fenced blocks -> static SVG (via mermaid-cli), markdown -> HTML (via marked).
// The PDF prints one long paginated document; the site publishes one page per
// source file with persistent navigation, which is what reference-during-play
// actually wants.
//
// Two things the site does that the PDF cannot:
//   - every location code in backticks (`FA.17`) becomes a link to that stub,
//     wherever in the corpus it is written;
//   - the region list is filterable from the keyboard.
//
// Diagrams are pre-rendered to inline SVG rather than shipped as mermaid plus a
// CDN script, so the site works offline once loaded and needs no third-party
// requests at the table.
//
// Scope: play content only — the setting outline, the 22 regions, the block
// documents and the setting relational diagram. Process documents (HANDOFF,
// PROCEDURES_AND_RULES, RECONCILIATION, DECISIONS, OPEN_QUESTIONS) are
// authoring instruments and are not
// published.
//
// This script never writes to or modifies any content file — only OUT_DIR.

