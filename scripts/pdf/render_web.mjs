let diagramCount = 0;
let renderFailures = 0;

function renderMermaidToSvg(code) {
  diagramCount += 1;
  const inFile = path.join(workDir, `diagram-${diagramCount}.mmd`);
  const outFile = path.join(workDir, `diagram-${diagramCount}.svg`);
  writeFileSync(inFile, code);
  try {
    execFileSync(MMDC, ["-i", inFile, "-o", outFile, "-p", puppeteerConfigPath, "-b", "transparent"], {
      stdio: ["ignore", "ignore", "pipe"],
    });
  } catch (e) {
    renderFailures += 1;
    console.error(`  diagram ${diagramCount}: mermaid render failed — ${e.stderr?.toString().trim() || e.message}`);
    return `<div class="diagram-error">[diagram ${diagramCount} failed to render — see build log]</div>`;
  }
  return `<div class="diagram">${readFileSync(outFile, "utf8")}</div>`;
}

// ---------------------------------------------------------------------------
// HTML assembly
// ---------------------------------------------------------------------------
function escapeHtml(s) {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
          .replace(/"/g, "&quot;");
}

const CODE_SPAN_RE = /<code>([A-Z]{1,2}\.[0-9]+[a-z]?)<\/code>/g;

// Post-process marked's output, line by line:
//   - stub headings get an id, so codes are linkable targets;
//   - every other code span that names a known location becomes a link.
// marked emits each heading on its own line, which is what makes the
// "don't self-link a heading" rule cheap to enforce.
function linkifyAndAnchor(html, currentSlug) {
  const out = [];
  for (const line of html.split("\n")) {
    const headingMatch = /^<h3[^>]*><code>([A-Z]{1,2}\.[0-9]+[a-z]?) /.exec(line);
    if (headingMatch) {
      const code = headingMatch[1];
      let anchored = line.replace(/^<h3([^>]*)>/, `<h3$1 id="${code}" class="stub">`);
      // Link any *other* codes in the heading, but not the stub's own code.
      let seenSelf = false;
      anchored = anchored.replace(CODE_SPAN_RE, (whole, c) => {
        if (c === code && !seenSelf) { seenSelf = true; return whole; }
        return linkFor(c, whole, currentSlug);
      });
      out.push(anchored);
      continue;
    }
    out.push(line.replace(CODE_SPAN_RE, (whole, c) => linkFor(c, whole, currentSlug)));
  }
  return out.join("\n");
}

function linkFor(code, whole, currentSlug) {
  const target = codeIndex.get(code);
  if (!target) return whole;   // undefined code — leave it plain, M1 will catch it
  const href = target.slug === currentSlug ? `#${code}` : `${target.slug}.html#${code}`;
  const title = escapeHtml(`${code} ${target.name}`);
  return `<a class="code-ref" href="${href}" title="${title}">${whole}</a>`;
}

function navHtml(currentSlug) {
  const groups = [];
  for (const page of pages) {
    let g = groups.find((x) => x.name === page.group);
    if (!g) { g = { name: page.group, items: [] }; groups.push(g); }
    g.items.push(page);
  }
  const parts = [`<nav class="sidebar" aria-label="Contents">`];
  parts.push(`<a class="brand" href="index.html">Drakenhold</a>`);
  parts.push(
    `<input type="search" id="nav-filter" class="nav-filter" placeholder="Filter (press /)" ` +
    `aria-label="Filter contents" autocomplete="off">`
  );
  for (const g of groups) {
    parts.push(`<div class="nav-group"><h2>${escapeHtml(g.name)}</h2><ul>`);
    for (const p of g.items) {
      const cls = p.slug === currentSlug ? ` class="current"` : "";
      parts.push(`<li${cls}><a href="${p.slug}.html">${escapeHtml(p.title)}</a></li>`);
    }
    parts.push(`</ul></div>`);
  }
  parts.push(`<div class="nav-group"><h2>Print</h2><ul>`);
  parts.push(`<li><a href="Drakenhold_Playbook.pdf">The Playbook, as PDF</a></li>`);
  parts.push(`</ul></div>`);
  parts.push(`</nav>`);
  return parts.join("\n");
}

function shell({ title, currentSlug, body, footer = "" }) {
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(title)} · Drakenhold</title>
<link rel="stylesheet" href="assets/site.css">
</head>
<body>
<button class="nav-toggle" aria-label="Contents" aria-expanded="false">☰</button>
${navHtml(currentSlug)}
<main>
${body}
${footer}
</main>
<script src="assets/site.js" defer></script>
</body>
</html>
`;
}

